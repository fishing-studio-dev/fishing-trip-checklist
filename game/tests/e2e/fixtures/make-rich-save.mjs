// Builds the playtest save: the real M1 save (m1-save.json), migrated by the
// game's own loader, with funds raised to 100,000G so the boat purchase can be
// tried right away. Writes tests/e2e/fixtures/m2-rich-save.json and the copy
// the game offers in its menus (src/ui/playtestSave.js).
// Run: node tests/e2e/fixtures/make-rich-save.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { loadSave, writeSave, memoryStorage, KEYS } from '../../../src/core/save.js';

const dir = path.dirname(fileURLToPath(import.meta.url));
const st = memoryStorage({ [KEYS.main]: fs.readFileSync(path.join(dir, 'm1-save.json'), 'utf8') });
const r = loadSave(st);
if (r.status !== 'ok') throw new Error(`m1 fixture did not load: ${r.status}`);
const rich = { ...r.profile, funds: 100000 };
const out = memoryStorage();
const w = writeSave(out, rich, 0, '2026-11-23T00:00:00.000Z');
if (!w.ok) throw new Error(w.error);
const raw = out.getItem(KEYS.main);
fs.writeFileSync(path.join(dir, 'm2-rich-save.json'), raw);
fs.writeFileSync(
  path.join(dir, '..', '..', '..', 'src', 'ui', 'playtestSave.js'),
  `// 試遊用セーブ（M1まで遊んだ進行・小型和船・曳縄具付き・資金100,000G）。\n// Generated by tests/e2e/fixtures/make-rich-save.mjs — do not edit by hand.\nexport const PLAYTEST_SAVE = ${JSON.stringify(raw)};\n`,
);
console.log('wrote m2-rich-save.json', rich.funds, rich.boat.model);
